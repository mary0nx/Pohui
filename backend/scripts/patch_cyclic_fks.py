"""Alembic autogenerate skips use_alter foreign keys; append them to a migration file.

Usage: python scripts/patch_cyclic_fks.py migrations/versions/<file>.py
"""

import sys

FKS = [
    ("fk_users_active_family_id_families", "users", "families", "active_family_id"),
    (
        "fk_transactions_scheduled_payment_id_scheduled_payments",
        "transactions",
        "scheduled_payments",
        "scheduled_payment_id",
    ),
]

path = sys.argv[1]
src = open(path, encoding="utf-8").read()
if "op.create_foreign_key(" in src:
    sys.exit(0)
# op.create_table() silently ignores use_alter constraints; drop them from create_table.
src = "".join(
    line for line in src.splitlines(keepends=True)
    if not ("ForeignKeyConstraint(" in line and "use_alter=True" in line)
)
up = "".join(
    f"    op.create_foreign_key({n!r}, {t!r}, {r!r}, [{c!r}], ['id'], ondelete='SET NULL')\n"
    for n, t, r, c in FKS
)
down = "".join(f"    op.drop_constraint({n!r}, {t!r}, type_='foreignkey')\n" for n, t, _, _ in FKS)
head, tail = src.split("def downgrade() -> None:\n")
head = head.replace("    # ### end Alembic commands ###", up + "    # ### end Alembic commands ###", 1)
tail = tail.replace(
    "    # ### commands auto generated by Alembic - please adjust! ###\n",
    "    # ### commands auto generated by Alembic - please adjust! ###\n" + down,
    1,
)
open(path, "w", encoding="utf-8").write(head + "def downgrade() -> None:\n" + tail)
